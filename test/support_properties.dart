import 'package:team_app/features/properties/domain/entities/property.dart';

Property makeProperty({
  String id = 'p1',
  String title = 'Modern Villa',
  TransactionType tx = TransactionType.buy,
  PropertyType type = PropertyType.villa,
  num price = 850000,
  String governorate = 'Tunis',
  String? city = 'La Marsa',
  String? area,
  VerificationStatus verification = VerificationStatus.approved,
  PropertyStatus status = PropertyStatus.published,
  int views = 0,
  int favorites = 0,
  DateTime? publishedAt,
  double? lat,
  double? lng,
  int? bedrooms = 4,
  int? bathrooms = 3,
  num? surface = 350,
  bool isStudio = false,
  bool isNewBuild = false,
  List<String> amenities = const [],
  List<String> images = const [],
}) =>
    Property(
      id: id,
      ownerId: 'o1',
      title: title,
      transactionType: tx,
      propertyType: type,
      price: price,
      currency: 'TND',
      governorate: governorate,
      city: city,
      area: area,
      status: status,
      verificationStatus: verification,
      views: views,
      favoritesCount: favorites,
      publishedAt: publishedAt,
      latitude: lat,
      longitude: lng,
      bedrooms: bedrooms,
      bathrooms: bathrooms,
      surface: surface,
      isStudio: isStudio,
      isNewBuild: isNewBuild,
      amenities: amenities,
      images: images,
    );
